function translateRegion(name) {
  if (seedLabelOverrides[name]) return seedLabelOverrides[name];
  if (regionOverrides[name]) return regionOverrides[name];
  if (/^[A-Za-z0-9 .-]+$/.test(name)) return name;

  let value = name;
  const rules = [
    [/^\u0645\u062f\u064a\u0646\u0629 /, ''],
    [/^\u0627\u0644/, ''],
    [/ \u0627\u0644\u062c\u062f\u064a\u062f\u0629$/, ' New'],
    [/^\u0627\u0644\u0639\u0627\u0634\u0631 \u0645\u0646 \u0631\u0645\u0636\u0627\u0646$/, '10th of Ramadan'],
    [/^6 \u0623\u0643\u062a\u0648\u0628\u0631$/, '6th of October'],
  ];

  for (const [pattern, replacement] of rules) {
    value = value.replace(pattern, replacement);
  }

  value = value.trim();
  if (name.startsWith('\u0645\u062f\u064a\u0646\u0629 ')) {
    value = `${value} City`;
  }

  return value || name;
}

